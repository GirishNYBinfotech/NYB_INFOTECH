let a = 10
let b = 3

//ARITHMETIC OPERATORS
console.log("Arithmetic Operators")

console.log("Addition (+):", a + b)
console.log("Subtraction (-):", a - b)
console.log("Multiplication (*):", a * b)
console.log("Division (/):", a / b)
console.log("Modulus (%):", a % b)
console.log("Exponentiation (**):", a ** b)
//pre-increment/Decrement
let c = 5
console.log("Increment (++):", ++c)
console.log("Decrement (--):", --c)
//post-increment/Decrement
console.log("Increment (++):", c++)
console.log("Decrement (--):", c--)

//COMPARISON OPERATORS
console.log(" Comparison Operators ");
console.log("Equal (==):", 10=="10")
console.log("Not equal (!=):", 10!="5")
console.log("Strict equal (===):", 10==="10")
console.log("Strict not equal (!==):", 10!=="10")
console.log("Greater than (>):", a>b)
console.log("Less than (<):", a<b)
console.log("Greater than or equal (>=):", a>=b)
console.log("Less than or equal (<=):", a<=b)

//LOGICAL OPERATORS
console.log("Logical Operators");
let x = true;
let y = false;

console.log("Logical AND (&&):", x && y)
console.log("Logical OR (||):", x || y)
console.log("Logical NOT (!):", !x)
console.log("AND (true && true):", true && true)
console.log("OR (false || false):", false || false)
console.log("NOT (!false):", !false)
